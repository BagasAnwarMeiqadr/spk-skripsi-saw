import streamlit as st
import pandas as pd
import random

st.set_page_config(page_title="SPK Judul Skripsi", page_icon="🎓", layout="wide")

st.markdown("""
    <style>
    .main-title { font-size: 2.8rem; color: #1E88E5; font-weight: 800; text-align: center; margin-bottom: 0px; }
    .sub-title { font-size: 1.2rem; color: #616161; text-align: center; margin-bottom: 40px; }
    .stButton>button { background-color: #1E88E5; color: white; border-radius: 8px; padding: 10px 24px; font-size: 18px; font-weight: bold; }
    .stButton>button:hover { background-color: #1565C0; color: white; }
    </style>
""", unsafe_allow_html=True)

with st.sidebar:
    st.image("https://cdn-icons-png.flaticon.com/512/2941/2941120.png", width=120)
    st.header("⚙️ Panel Admin")
    st.write("Sistem Pendukung Keputusan Penentuan Judul Skripsi Teknik Informatika.")
    st.divider()
    st.info("💡 **Alur Sistem (Prototipe)**\n1. SAW memilih bidang terbaik.\n2. AI merangkai judul spesifik berdasarkan cerita minat mahasiswa.")

st.markdown('<p class="main-title">🎓 Sistem Rekomendasi Judul Skripsi</p>', unsafe_allow_html=True)
st.markdown('<p class="sub-title">Pemetaan kompetensi akademik dan minat riset mahasiswa.</p>', unsafe_allow_html=True)

# DATA DUMMY KRITERIA SAW
data_topik = {
    'Bidang Skripsi': ['Sistem Pakar / AI', 'Sistem Informasi Web', 'Jaringan Komputer / IoT', 'Data Science'],
    'Min_AI': [85, 60, 60, 80],       
    'Min_Web': [60, 85, 60, 70],      
    'Min_Jaringan': [60, 60, 85, 60]  
}
df_topik = pd.DataFrame(data_topik)

# DATABASE SIMULASI JUDUL UNIK (Nanti diganti API Generative AI sungguhan)
judul_ai = {
    'Sistem Pakar / AI': ["Penerapan Algoritma Naive Bayes untuk Klasifikasi...", "Sistem Pakar Diagnosa Penyakit Menggunakan Metode Certainty Factor...", "Analisis Sentimen Pengguna Twitter Terhadap..."],
    'Sistem Informasi Web': ["Sistem Informasi Geografis Pemetaan Fasilitas...", "Rancang Bangun E-Commerce Berbasis MERN Stack pada...", "Pengembangan Sistem Informasi Akademik Menggunakan Framework Laravel..."],
    'Jaringan Komputer / IoT': ["Implementasi Smart Home System Berbasis IoT...", "Analisis Quality of Service (QoS) pada Jaringan...", "Sistem Monitoring Suhu Server Room Menggunakan Raspberry Pi..."],
    'Data Science': ["Prediksi Penjualan Menggunakan Algoritma Regresi Linear...", "Segmentasi Pelanggan Menggunakan K-Means Clustering...", "Analisis Big Data Tren Pasar Saham Menggunakan..."]
}

st.markdown("### 📝 1. Masukkan Nilai Mata Kuliah Kamu")
col1, col2, col3 = st.columns(3)
with col1: nilai_ai = st.number_input("🤖 Kecerdasan Buatan (AI)", 0, 100, 75)
with col2: nilai_web = st.number_input("🌐 Pemrograman Web", 0, 100, 75)
with col3: nilai_jaringan = st.number_input("📡 Jaringan Komputer", 0, 100, 75)

st.markdown("### ✍️ 2. Ceritakan Minat Riset Kamu")
minat_user = st.text_area("Ceritakan spesifik minat kamu (Contoh: 'Saya suka dunia kesehatan dan ingin membuat sistem diagnosa' atau 'Saya tertarik bisnis UMKM')...", height=100)

if st.button("🚀 Analisis & Generate Judul", use_container_width=True):
    with st.spinner('Menghitung SAW & Generate AI...'):
        
        # PROSES SAW
        skor_akhir = []
        for index, row in df_topik.iterrows():
            skor = (((nilai_ai / row['Min_AI']) * 0.4) + ((nilai_web / row['Min_Web']) * 0.3) + ((nilai_jaringan / row['Min_Jaringan']) * 0.3)) * 100 
            skor_akhir.append(round(min(skor, 100.0), 2))
            
        df_topik['Skor (%)'] = skor_akhir
        df_hasil = df_topik.sort_values(by='Skor (%)', ascending=False)
        df_hasil.insert(0, 'Ranking', range(1, 1 + len(df_hasil)))
        
        # PROSES SIMULASI AI MENGAMBIL JUDUL UNIK
        bidang_pemenang = df_hasil.iloc[0]['Bidang Skripsi']
        
        # Mengambil judul acak dari database simulasi berdasarkan bidang pemenang
        rekomendasi_judul = random.choice(judul_ai[bidang_pemenang])
        if minat_user:
            rekomendasi_judul += f" (Fokus studi kasus disesuaikan dengan cerita minat Anda)"

    st.divider()
    st.success("🎉 Analisis Selesai! Berikut adalah hasil *Generate* judul terbaik untukmu:")
    
    res_col1, res_col2 = st.columns([1, 1])
    
    with res_col1:
        st.metric(label="🏆 Bidang Keahlian Sesuai SAW", value=bidang_pemenang, delta=f"{df_hasil.iloc[0]['Skor (%)']}% Cocok", delta_color="normal")
        st.info(f"**Rekomendasi Judul (Generated by AI):**\n\n*{rekomendasi_judul}*")
        
    with res_col2:
        st.write("**Tabel Perhitungan Matriks SAW:**")
        # Kode background_gradient sudah aman karena matplotlib sudah ditambahkan di requirements
        st.dataframe(df_hasil.style.background_gradient(cmap='Blues', subset=['Skor (%)']), hide_index=True, use_container_width=True)
